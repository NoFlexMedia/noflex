// Packs the Phosphor icons the app draws, and the brand mark, into one white
// sprite sheet the renderer tints. One texture: every icon on screen batches
// into a draw, and the renderer never has to rasterize an SVG, which tvOS can't.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { Resvg } from "@resvg/resvg-js";

const CELL = 96;
const COLUMNS = 8;

// name -> weight. `fill` is for transport controls and ratings, as on the web.
const ICONS = {
  "arrow-clockwise": "regular", "arrow-counter-clockwise": "regular", "arrow-right": "regular", backspace: "regular",
  "book-open": "regular", books: "regular", broadcast: "regular", "cards-three": "regular", "caret-right": "regular", "circle-notch": "bold",
  check: "bold", "check-circle": "regular", "closed-captioning": "regular", "clock-counter-clockwise": "regular", "film-strip": "regular",
  gear: "regular", globe: "regular", heart: "regular", "heart-fill": "fill", house: "regular", image: "regular", info: "regular",
  "lock-key": "regular", "magnifying-glass": "regular", "music-notes": "regular", pause: "fill", play: "fill", "shield-check": "regular",
  "sign-out": "regular", "skip-forward": "fill", sparkle: "regular", stack: "regular", star: "fill", subtitles: "regular", television: "regular",
  translate: "regular", user: "regular", "warning-circle": "regular", "arrow-up": "regular", x: "regular",
};

const source = (name, weight) => readFileSync(`node_modules/@phosphor-icons/core/assets/${weight}/${name.replace(/-fill$/, "")}${weight === "regular" ? "" : `-${weight}`}.svg`, "utf8").replace(/fill="currentColor"/, 'fill="#ffffff"');
const inner = (svg) => svg.replace(/<!--[\s\S]*?-->\s*/, "").replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");

const names = Object.keys(ICONS).sort();
const rows = Math.ceil(names.length / COLUMNS);
const cells = names.map((name, index) => {
  const x = (index % COLUMNS) * CELL;
  const y = Math.floor(index / COLUMNS) * CELL;
  return { name, x, y, body: `<svg x="${x}" y="${y}" width="${CELL}" height="${CELL}" viewBox="0 0 256 256" fill="#ffffff">${inner(source(name, ICONS[name]))}</svg>` };
});
const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="${COLUMNS * CELL}" height="${rows * CELL}">${cells.map((cell) => cell.body).join("")}</svg>`;
writeFileSync("public/icons.png", new Resvg(sheet, { fitTo: { mode: "original" } }).render().asPng());

// Colored, so it stays out of the tinted sheet.
const brand = readFileSync("../web/static/favicon.svg", "utf8");
const mark = (size) => new Resvg(brand, { fitTo: { mode: "width", value: size } }).render().asPng();
writeFileSync("public/brand.png", mark(256));

// What each store's launcher draws.
const write = (path, png) => { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, png); };
write("hosts/tizen/icon.png", mark(512));
write("hosts/webos/icon.png", mark(80));
write("hosts/webos/largeIcon.png", mark(130));
write("hosts/android/app/src/main/res/mipmap-xhdpi/ic_launcher.png", mark(192));
// Full-bleed for iOS, which rounds it itself; the mark on the page's dark for Android TV's 320×180 tile.
const placed = (x, y, size) => `<svg x="${x}" y="${y}" width="${size}" height="${size}" viewBox="0 0 64 64">${inner(brand)}</svg>`;
const canvas = (width, height, fill, body) => new Resvg(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><rect width="${width}" height="${height}" fill="${fill}"/>${body}</svg>`).render().asPng();
write("hosts/nativescript/App_Resources/iOS/Assets.xcassets/AppIcon.appiconset/icon.png", canvas(1024, 1024, "#d4ff5a", placed(0, 0, 1024)));
write("hosts/android/app/src/main/res/drawable-xhdpi/banner.png", canvas(320, 180, "#07080b", placed(110, 40, 100)));

const table = cells.map((cell) => `  "${cell.name}": [${cell.x}, ${cell.y}],`).join("\n");
writeFileSync("src/lib/icons.generated.ts", `// SPDX-License-Identifier: AGPL-3.0-only
//
// Generated by scripts/build-icons.mjs. Each icon's top-left in public/icons.png.

export const ICON_CELL = ${CELL};
export const ICON_CELLS = {
${table}
} as const;

export type IconName = keyof typeof ICON_CELLS;
`);
console.log(`${names.length} icons, ${COLUMNS * CELL}×${rows * CELL}`);
